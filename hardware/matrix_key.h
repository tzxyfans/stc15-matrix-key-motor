/*
 * matrix_key.h —— 4×4 矩阵按键模块对外接口
 *
 * ============================================================================
 * 硬件接线（开发板矩阵按键）
 * ============================================================================
 *   ⚠️ 重要提醒：开发板上的跳线 J5 必须短接到【矩阵按键侧】的两个跳线端子！
 *   如果 J5 短接在独立按键侧，矩阵按键的行线/列线不会连通，扫描永远读不到按键。
 *
 *   行线（单片机输出扫描信号，逐行拉低）：
 *     ROW1 = P3.0    ROW2 = P3.1    ROW3 = P3.2    ROW4 = P3.3
 *
 *   列线（单片机输入读取状态，按键按下时被拉低）：
 *     COL1 = P4.4    COL2 = P4.2    COL3 = P3.5    COL4 = P3.4
 *
 *   4×4 按键布局（行×列）：
 *     ┌─────┬─────┬─────┬─────┐
 *     │  7  │  8  │  9  │  A  │  ← ROW1
 *     ├─────┼─────┼─────┼─────┤
 *     │  4  │  5  │  6  │  B  │  ← ROW2
 *     ├─────┼─────┼─────┼─────┤
 *     │  1  │  2  │  3  │  C  │  ← ROW3
 *     ├─────┼─────┼─────┼─────┤
 *     │  *  │  0  │  #  │  D  │  ← ROW4
 *     └─────┴─────┴─────┴─────┘
 *       COL1  COL2  COL3  COL4
 *
 * ============================================================================
 * 扫描原理（逐行扫描法，面向初学者）
 * ============================================================================
 *   1. 4 条行线默认全部输出高电平
 *   2. 把第 N 行拉低（其他行保持高），读 4 条列线
 *   3. 如果某列读到低电平 → 第 N 行该列的按键被按下
 *   4. 逐行重复（N=0,1,2,3），就能定位 16 个按键中的任意一个
 *
 *   为什么叫"矩阵"：16 个按键排成 4×4 矩阵，只需 8 个 IO（4 行+4 列），
 *   比独立按键省一半 IO。这是单片机扩展按键的常用手法。
 *
 * ============================================================================
 * 对外接口
 * ============================================================================
 *   MatrixKey_Init   初始化行线/列线端口为准双向口
 *   MatrixKey_Scan   边沿检测：返回"刚按下"的键值，按一次只触发一次
 *                    无事件时返回 KEY_NONE。用于自动模式（按一次触发一次）
 *   MatrixKey_Read   电平检测：返回当前按住的键值，无消抖
 *                    无键返回 KEY_NONE。用于点动模式（按住动、松开停）
 *
 *   两个函数的区别：
 *     Scan → 下降沿事件（按一次报一次，长按不重复），内部有10ms消抖
 *     Read → 原始电平状态（按住一直报，松开变无键），无消抖
 */
#ifndef __MATRIX_KEY_H__
#define __MATRIX_KEY_H__

#include <STC15.H>

#define KEY_NONE  0xFF         /* 无按键按下的返回值（0xFF不会和任何键值冲突）*/

void MatrixKey_Init(void);            /* 初始化矩阵按键端口 */
unsigned char MatrixKey_Scan(void);   /* 边沿检测：按下事件，无事件返回KEY_NONE */
unsigned char MatrixKey_Read(void);   /* 电平检测：当前按住状态，无键返回KEY_NONE */

#endif /* __MATRIX_KEY_H__ */