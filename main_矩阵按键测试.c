/*
 * 矩阵按键测试 —— 4×4 矩阵按键扫描 + OLED 显示
 * 目标芯片：STC15F2K60S2 / IAP15F2K61S2
 *
 * ============================================================================
 * ⚠️ 重要提醒（开发板跳线设置）
 * ============================================================================
 *   开发板上的跳线 J5 必须短接到【矩阵按键侧】的两个跳线端子！
 *   如果 J5 接在独立按键侧，矩阵按键的行线/列线不会连通，扫描读不到按键。
 *   这是矩阵按键实验最常见的"按键无反应"原因，请务必先检查跳线！
 *
 * ============================================================================
 * 功能说明
 * ============================================================================
 *   上电后 OLED 显示测试界面，按下矩阵按键的任意键，
 *   OLED 第三行显示该按键的字符值（'0'~'9','A'~'D','*','#'）。
 *
 * ============================================================================
 * 矩阵按键接线（由 matrix_key 模块统一定义）
 * ============================================================================
 *   行线：ROW1=P3.0  ROW2=P3.1  ROW3=P3.2  ROW4=P3.3
 *   列线：COL1=P4.4  COL2=P4.2  COL3=P3.5  COL4=P3.4
 *
 *   4×4 布局：
 *     ┌───┬───┬───┬───┐
 *     │ 7 │ 8 │ 9 │ A │
 *     ├───┼───┼───┼───┤
 *     │ 4 │ 5 │ 6 │ B │
 *     ├───┼───┼───┼───┤
 *     │ 1 │ 2 │ 3 │ C │
 *     ├───┼───┼───┼───┤
 *     │ * │ 0 │ # │ D │
 *     └───┴───┴───┴───┘
 *
 * ============================================================================
 * OLED 显示布局（128×64，4 行每行 16 像素高）
 * ============================================================================
 *   第一行 Y=0  ：Matrix Key Test   （标题，居中）
 *   第二行 Y=16 ：Key Value:        （标签）
 *   第三行 Y=32 ：X                 （按键值，大字显示）
 *   第四行 Y=48 ：Press any key...  （提示）
 */
#include "STC15.H"
#include "matrix_key.h"
#include "delay.h"
#include "OLED_STC15.h"

void main(void)
{
    unsigned char key;                /* 扫描到的键值，无键时为KEY_NONE(0xFF) */

    /* ---- 初始化 ---- */
    MatrixKey_Init();                 /* 矩阵按键端口初始化 */
    OLED_Init();
    OLED_Clear();

    /* ---- 第一行：Matrix Key Test（居中）---- */
    /* "Matrix Key Test" = 15字符 = 120px，居中 X=(128-120)/2=4 */
    OLED_ShowString(4, 0, "Matrix Key Test");

    /* ---- 第二行：Key Value: ---- */
    OLED_ShowString(0, 16, "Key Value:");

    /* ---- 第四行：Press any key... ---- */
    OLED_ShowString(0, 48, "Press any key...");

    /* 第三行初始显示 '-' 表示无按键 */
    OLED_ShowString(0, 32, "-");
    OLED_Update();

    /* ---- 主循环：扫描按键，显示按键值 ---- */
    while (1)
    {
        key = MatrixKey_Scan();       /* 扫描矩阵按键 */

        if (key != KEY_NONE)          /* 有按键按下（KEY_NONE=0xFF表示无键）*/
        {
            /*
             * 显示按键值：
             *   先清第三行旧内容（X=0~16, Y=32~48），再写新字符
             *   key 是 ASCII 字符（'0'~'9','A'~'D','*','#'），直接显示
             */
            OLED_ClearArea(0, 32, 16, 16);   /* 清旧按键值区域 */
            OLED_ShowChar(0, 32, key);        /* 显示新按键值 */
            OLED_Update();                    /* 刷屏 */
        }
    }
}
