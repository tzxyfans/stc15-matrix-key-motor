/*
 * 电机控制系统 —— 自动 / 点动双模式整合 + 工程安全约束 + OLED 状态显示
 * 目标芯片：STC15F2K60S2 / IAP15F2K61S2
 * 晶振：11.0592MHz（内部 IRC）
 *
 * 功能：
 *   ① S7 键：模式切换键（自动模式 ↔ 点动模式），仅电机停止时才允许切换
 *   ② 自动模式下：
 *        S4 按下放开 → 正转；S6 按下放开 → 反转；S5 按下放开 → 惯性停转
 *   ③ 点动模式下：
 *        S4 按下 → 正转，放开 → 惯性停转；S6 按下 → 反转，放开 → 惯性停转
 *   ④ OLED 第一行：标题"电机控制系统"
 *   ⑤ OLED 第二行："运行状态："正转 / 反转 / 停止
 *   ⑥ OLED 第三行："当前模式：自动 / 点动"
 *
 * 接线：
 *   按键：S7 = P3.0，S6 = P3.1，S5 = P3.2，S4 = P3.3（独立按键，按下为低电平）
 *   电机：PWM = P4.6，DIR = P3.7，BRAKE = P4.7
 *   OLED（I2C）：SCL = P0.7，SDA = P0.6
 *
 * 显示布局：
 *   第一行(y=0)：  电机控制系统        ← 标题
 *   第二行(y=16)： 运行状态：停止      ← 标签开机画一次，状态由主循环刷新
 *   第三行(y=32)： 当前模式：自动      ← 标签开机画一次，模式由主循环刷新
 *
 * 状态机标志位：
 *   mode  —— 控制模式：1 = 自动模式，0 = 点动模式（开机默认自动）
 *   state —— 电机运行状态：0 = 停止，1 = 正转，2 = 反转（开机默认停止）
 *   两个标志位配合：mode 决定走哪套控制逻辑，state 记录电机当前动作并驱动显示。
 *
 * 三条工程安全约束（本版重点）：
 *   ① 正转时不能直接反转（反之亦然）：必须先停止再换向
 *        工程意义：带电直接换向，电枢电流瞬间反向，会产生很大的电流冲击
 *                  （甚至接近 2 倍启动电流），可能烧毁驱动管或损坏电机绕组。
 *        实现：自动模式方向键触发前检查 state，正转中按反转键无效，反之同理；
 *              点动模式同时按两个方向键 → 强制停止，放开一键后另一键才生效，
 *              天然产生"停止"过渡，不会带电直接换向。
 *   ② 运动时不能切换控制模式：S7 仅在 state==0（停止）时才切换 mode
 *        工程意义：带电切换控制逻辑可能让电机失控——例如点动正转中切到自动模式，
 *                  此时按键已放开但自动模式不依赖电平，电机会保持正转无法停止。
 *        实现：S7 放开事件里先判 state==0，运动中按 S7 无效。
 *   ③ 不能同时按下多个方向控制按键：
 *        工程意义：同时给正转和反转信号，驱动器两端逻辑冲突，可能造成桥臂直通
 *                  短路，烧毁驱动管。
 *        实现：点动模式显式检测 S4&&S6 同时按下 → 强制惯性停转（互锁保护）；
 *              自动模式 if-else if 互斥 + 方向互锁，先放开者生效，后放开者被拒。
 */
#include "key.h"
#include "motor.h"
#include "OLED_STC15.h"

unsigned char mode = 1;       /* 控制模式：1 = 自动模式，0 = 点动模式（开机默认自动） */
unsigned char state = 0;      /* 电机运行状态：0 = 停止，1 = 正转，2 = 反转（开机默认停止） */

void main(void)
{
    Key_Init();                /* 按键初始化：准双向口 + 历史状态清零 */
    Motor_Init();              /* 电机初始化：准双向口，默认惯性停转（安全状态） */
    OLED_Init();               /* OLED 初始化（内部先延时，待供电稳定） */

    OLED_Clear();              /* 清空显存 */
    /* 第一行：标题"电机控制系统" */
    OLED_ShowChinese(16, 0, "电机控制系统");
    /* 第二行：标签"运行状态:"，开机只画一次 */
    OLED_ShowMixedText(0, 16, "运行状态:");
    OLED_ShowChinese(72, 16, "停止");       /* 初始状态：停止 */
    /* 第三行：标签"当前模式:"，开机只画一次 */
    OLED_ShowMixedText(0, 32, "当前模式:");
    OLED_ShowChinese(72, 32, "自动");       /* 初始模式：自动 */
    OLED_Update();             /* 把界面先刷上屏 */

    while (1)
    {
        /*
         * 第一阶段：模式切换（S7 放开事件）
         * 安全约束②：仅当 state==0（电机已停止）时才允许切换 mode，
         *           运动中按 S7 无效，避免带电切换控制逻辑导致电机失控。
         */
        if (Key_S7_Released() == 1)
        {
            if (state == 0)
            {
                if (mode == 1)
                {
                    mode = 0;           /* 自动 → 点动 */
                }
                else
                {
                    mode = 1;           /* 点动 → 自动 */
                }
            }
            /* state != 0 时按 S7 无效，模式不变 */
        }

        /*
         * 第二阶段：按 mode 标志位分发控制逻辑
         */
        if (mode == 1)
        {
            /*
             * 自动模式：放开事件触发 + 方向互锁
             *   S4 放开 → 若非反转中则正转（安全约束①：反转中按正转键无效）
             *   S6 放开 → 若非正转中则反转（安全约束①：正转中按反转键无效）
             *   S5 放开 → 惯性停转（任意状态都可停止）
             * if-else if 互斥保证同一帧只响应一个键（安全约束③）
             */
            if (Key_S4_Released() == 1)
            {
                if (state != 2)         /* 非反转中，允许正转 */
                {
                    Motor_Forward();
                    state = 1;
                }
            }
            else if (Key_S6_Released() == 1)
            {
                if (state != 1)         /* 非正转中，允许反转 */
                {
                    Motor_Reverse();
                    state = 2;
                }
            }
            else if (Key_S5_Released() == 1)
            {
                Motor_Coast();
                state = 0;
            }
        }
        else
        {
            /*
             * 点动模式：电平检测 + 同时按下互锁
             *   S4、S6 同时按下 → 强制惯性停转（安全约束③：互锁保护）
             *   仅 S4 按下 → 正转
             *   仅 S6 按下 → 反转
             *   都放开 → 惯性停转
             * 同时按下时强制停止，放开一键后另一键才生效，
             * 天然产生停止过渡，不会带电直接换向（安全约束①）
             */
            unsigned char s4 = Key_S4_Down();
            unsigned char s6 = Key_S6_Down();
            if ((s4 == 1) && (s6 == 1))
            {
                Motor_Coast();          /* 互锁：同时按下两个方向键，强制停止 */
                state = 0;
            }
            else if (s4 == 1)
            {
                Motor_Forward();
                state = 1;
            }
            else if (s6 == 1)
            {
                Motor_Reverse();
                state = 2;
            }
            else
            {
                Motor_Coast();
                state = 0;
            }
        }

        /*
         * 第三阶段：显示刷新
         * 第二行根据 state 刷新运行状态，第三行根据 mode 刷新控制模式，
         * 写显存后由 OLED_Update 一次性刷到屏幕。
         */
        if (state == 1)
        {
            OLED_ShowChinese(72, 16, "正转");
        }
        else if (state == 2)
        {
            OLED_ShowChinese(72, 16, "反转");
        }
        else
        {
            OLED_ShowChinese(72, 16, "停止");
        }

        if (mode == 1)
        {
            OLED_ShowChinese(72, 32, "自动");
        }
        else
        {
            OLED_ShowChinese(72, 32, "点动");
        }
        OLED_Update();
    }
}
